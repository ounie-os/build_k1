extern int TSK2;

int create_tasks()
{
    struct timespec wakeup;
    clock_gettime(CLOCK_MONOTONIC, &wakeup);

    while (1) {
        wakeup.tv_nsec += 4000000;
        if (wakeup.tv_nsec >= 1000000000L) {
            wakeup.tv_nsec -= 1000000000L;
            wakeup.tv_sec++;
        }
        clock_nanosleep(CLOCK_MONOTONIC, TIMER_ABSTIME, &wakeup, NULL);
        TSK2 =1;
        plc_run();
    }
}
