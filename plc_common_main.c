void __run(void)
{

    __retrieve_0();
    __retrieve_1();

    /*__retrieve_debug();*/

#ifdef WIN32R
    PLC_GetTimeNow(&time_now);
    PLC_TimeDelay(&__CURRENT_TIME,&time_elapsed);
    HOTKEY_F5 = GetKeyState(VK_F5);
    if(debug_state==1)
    {
		__tick++;
		if (greatest_tick_count__)
        __tick %= greatest_tick_count__;
        config_run__(__tick);
    }
    else
	{
		if( HOTKEY_F5<0 && !debug_step_in)
		{
			config_run__(__tick);
			debug_step_in = 1;
		}
		else
		{
			PLC_TimeMinus(&time_now,&time_last,&time_elasped_tmp);
			PLC_TimeAdd(&time_elapsed,&time_elasped_tmp,&time_elapsed);
			debug_step_in = 0;
		}
    }
    time_last.tv_sec = time_now.tv_sec;
    time_last.tv_nsec = time_now.tv_nsec;  
#else
    __tick++;
    if (greatest_tick_count__)
        __tick %= greatest_tick_count__;
    config_run__(__tick);
#endif
    __publish_debug();
    __publish_1();
    __publish_0();
}

/*
 * Initialize variables according to PLC's default values,
 * and then init plugins with that values
 **/
int __init()
{
    int res = 0;
    init_level = 0;
    config_init__();
    __init_debug();
    init_level=1; if((res = __init_0())){return res;}
    init_level=2; if((res = __init_1())){return res;}
    return res;
}
/*
 * Calls plugin cleanup proc.
 **/
void __cleanup(void)
{
    if(init_level >= 2) __cleanup_1();
    if(init_level >= 1) __cleanup_0();
    __cleanup_debug();
}

